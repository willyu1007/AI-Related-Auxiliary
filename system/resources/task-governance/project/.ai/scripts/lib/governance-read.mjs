function listImmediateChildDirs(dirPath) {
  let entries;
  try {
    entries = fs.readdirSync(dirPath, { withFileTypes: true });
  } catch (error) {
    // A directory that does not exist is a legitimate empty state (governance not installed
    // there yet). Any other failure is unreadable evidence and must not degrade to "empty".
    if (error?.code === 'ENOENT') return [];
    throw new Error(
      `Cannot read task-evidence directory ${toPosix(dirPath)}: ${error?.code || error?.message || error}.`
    );
  }
  return entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort((a, b) => a.localeCompare(b));
}

export function getBundleStatusFromStatusDoc(statusRaw, statusPath = '01-status.md') {
  const lines = normalizeEol(statusRaw).split('\n');
  let inProgress = false;

  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('#')) {
      if (/^##\s+Progress\s*$/i.test(trimmed)) {
        inProgress = true;
        continue;
      }
      if (inProgress && /^##\s+/.test(trimmed)) break;
    }
    if (!inProgress) continue;

    const match = trimmed.match(/^\-\s*State\s*:\s*(.+)\s*$/i);
    if (!match) continue;
    const value = String(match[1] || '').trim();
    if (value.includes('|')) {
      return { status: null, error: 'State must be a single value (not an enum hint).' };
    }
    if (!BUNDLE_STATUS.has(value)) {
      const hint = BUNDLE_STATUS.has(value.toLowerCase()) ? ' (status values must be lowercase)' : '';
      return {
        status: null,
        error: `Invalid State value: "${value}". Allowed: ${[...BUNDLE_STATUS].join(', ')}${hint}`,
      };
    }
    return { status: value, error: null };
  }

  return {
    status: null,
    error: `Missing "## Progress" / "- State: <status>" in ${toPosix(statusPath)}.`,
  };
}

export function getMarkdownSectionLines(markdownRaw, heading) {
  const lines = normalizeEol(markdownRaw).split('\n');
  const target = String(heading || '').trim().toLowerCase();
  const result = [];
  let inSection = false;

  for (const line of lines) {
    const match = line.trim().match(/^##\s+(.+?)\s*$/);
    if (match) {
      if (inSection) break;
      inSection = String(match[1] || '').trim().toLowerCase() === target;
      continue;
    }
    if (inSection) result.push(line);
  }
  return result;
}

export function cleanMarkdownValue(value) {
  return String(value || '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join(' ')
    .trim();
}

function createResumeTextLimiter() {
  const fields = [];

  function mark(field) {
    if (!fields.includes(field)) fields.push(field);
  }

  function text(value, maxChars, field) {
    if (value === null || value === undefined) return value;
    const raw = String(value);
    if (raw.length <= maxChars) return raw;
    mark(field);
    return `${raw.slice(0, Math.max(0, maxChars - 1))}…`;
  }

  return { fields, mark, text };
}

function getMarkdownSectionText(markdownRaw, heading) {
  return cleanMarkdownValue(getMarkdownSectionLines(markdownRaw, heading).join('\n'));
}

function getMarkdownListField(markdownRaw, heading, field) {
  const target = String(field || '').trim().toLowerCase();
  for (const line of getMarkdownSectionLines(markdownRaw, heading)) {
    const match = line.trim().match(/^\-\s*([^:]+)\s*:\s*(.*)$/);
    if (!match || String(match[1] || '').trim().toLowerCase() !== target) continue;
    return cleanMarkdownValue(match[2] || '');
  }
  return '';
}

function parseTableRowCells(line) {
  const trimmed = String(line || '').trim();
  if (!trimmed.startsWith('|') || !trimmed.endsWith('|')) return null;
  // Split on unescaped pipes only: `\|` is literal cell content and `\\|` is a literal
  // backslash followed by a cell boundary, matching how markdownCell escapes on render.
  const cells = [];
  let current = '';
  for (let index = 1; index < trimmed.length - 1; index++) {
    const char = trimmed[index];
    if (char === '\\' && index + 1 < trimmed.length - 1) {
      const next = trimmed[index + 1];
      current += next === '|' ? '|' : char + next;
      index++;
      continue;
    }
    if (char === '|') {
      cells.push(current.trim());
      current = '';
      continue;
    }
    current += char;
  }
  cells.push(current.trim());
  return cells;
}

function isTableSeparatorRow(cells) {
  return cells !== null && cells.length > 0 && cells.every((cell) => /^:?-{3,}:?$/.test(cell));
}

function getPitfallTableItems(markdownRaw, limit) {
  // The header is structural — any table row directly followed by a separator row — so template
  // display wording cannot break parsing. Data columns follow the current template order:
  // hazard, evidence, prevention, removal condition.
  const items = [];
  const lines = normalizeEol(markdownRaw).split('\n');
  let inTable = false;

  for (let index = 0; index < lines.length; index++) {
    const cells = parseTableRowCells(lines[index]);
    if (cells === null) {
      inTable = false;
      continue;
    }
    if (!inTable) {
      if (isTableSeparatorRow(parseTableRowCells(lines[index + 1]))) {
        inTable = true;
        index++;
      }
      continue;
    }
    const hazard = cleanMarkdownValue(cells[0]);
    if (!hazard) continue;
    const prevention = cleanMarkdownValue(cells[2]);
    items.push(prevention ? `${hazard} — ${prevention}` : hazard);
    if (items.length >= limit) break;
  }
  return items;
}

function getMarkdownChecklistStats(markdownRaw, heading) {
  const items = getMarkdownChecklistItems(markdownRaw, heading);
  return {
    total: items.length,
    checked: items.filter((item) => item.checked).length,
  };
}

export function getMarkdownChecklistItems(markdownRaw, heading) {
  const items = [];
  for (const line of getMarkdownSectionLines(markdownRaw, heading)) {
    const match = line.trim().match(/^\-\s*\[(x|X|\s)\]\s+(.+)$/);
    if (!match) continue;
    const text = cleanMarkdownValue(match[2]);
    if (!text) continue;
    items.push({ checked: String(match[1]).toLowerCase() === 'x', text });
  }
  return items;
}

