export function toPosix(value) {
  return String(value).replace(/\\/g, '/');
}

export function normalizeEol(value) {
  return String(value || '').replace(/\r\n/g, '\n');
}

function markdownCell(value) {
  return String(value || '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|');
}

export function getAutoGeneratedContent(raw, blockId) {
  if (raw === null || raw === undefined) return null;
  const normalized = normalizeEol(raw);
  const start = `<!-- AUTO-GENERATED:START ${blockId} -->`;
  const end = `<!-- AUTO-GENERATED:END ${blockId} -->`;
  const startIndex = normalized.indexOf(start);
  const endIndex = normalized.indexOf(end);
  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) return null;
  return normalized.slice(startIndex + start.length, endIndex).trim();
}

export function renderDashboardProjection(registry) {
  const tasks = Array.isArray(registry?.tasks) ? registry.tasks : [];
  const counts = { planned: 0, inProgress: 0, blocked: 0, done: 0, archived: 0 };
  for (const task of tasks) {
    const status = String(task?.status || '');
    if (status === 'planned') counts.planned++;
    else if (status === 'in-progress') counts.inProgress++;
    else if (status === 'blocked') counts.blocked++;
    else if (status === 'done') counts.done++;
    else if (status === 'archived') counts.archived++;
  }
  return [
    '## Summary',
    '',
    `- Tasks: ${tasks.length} (planned: ${counts.planned}, in-progress: ${counts.inProgress}, blocked: ${counts.blocked}, done: ${counts.done}, archived: ${counts.archived})`,
    '',
    '## Recently registered or status-changed tasks',
    '',
    '| Task | Status | Feature | Dev Docs |',
    '| --- | --- | --- | --- |',
    ...tasks
      .slice()
      .sort((left, right) => String(right?.updated || '').localeCompare(String(left?.updated || '')))
      .slice(0, 20)
      .map((task) => {
        const label = `${task?.id || ''} ${task?.slug || ''}`.trim();
        return `| ${markdownCell(label)} | ${markdownCell(task?.status)} | ${markdownCell(task?.feature_id)} | ${markdownCell(task?.dev_docs_path)} |`;
      }),
    '',
  ].join('\n');
}

export function renderFeatureMap(registry) {
  const tasks = Array.isArray(registry?.tasks) ? registry.tasks : [];
  const features = Array.isArray(registry?.features) ? registry.features : [];
  const milestones = Array.isArray(registry?.milestones) ? registry.milestones : [];
  const tasksByFeature = new Map();
  for (const task of tasks) {
    const featureId = String(task?.feature_id || 'F-000');
    const grouped = tasksByFeature.get(featureId) || [];
    grouped.push(task);
    tasksByFeature.set(featureId, grouped);
  }

  const lines = ['# Feature Map', '', '<!-- AUTO-GENERATED:START feature-map -->'];
  for (const milestone of milestones.slice().sort((a, b) => String(a?.id || '').localeCompare(String(b?.id || '')))) {
    if (!milestone || typeof milestone !== 'object') continue;
    const milestoneId = String(milestone.id || '');
    lines.push(`## ${milestoneId} ${markdownCell(milestone.title)}`.trim(), '');
    lines.push(`- Status: ${markdownCell(milestone.status)}`);
    lines.push(`- Description: ${markdownCell(milestone.description) || '_No description recorded._'}`, '');
    const ownedFeatures = features
      .filter((feature) => feature && String(feature.milestone_id || '') === milestoneId)
      .sort((a, b) => String(a.id || '').localeCompare(String(b.id || '')));
    if (ownedFeatures.length === 0) {
      lines.push('_No Features._', '');
      continue;
    }
    for (const feature of ownedFeatures) {
      const featureId = String(feature.id || '');
      lines.push(`### ${featureId} ${markdownCell(feature.title)}`.trim(), '');
      lines.push(`- Status: ${markdownCell(feature.status)}`);
      lines.push(`- Description: ${markdownCell(feature.description) || '_No description recorded._'}`, '');
      const mappedTasks = (tasksByFeature.get(featureId) || [])
        .slice()
        .sort((a, b) => String(a?.id || '').localeCompare(String(b?.id || '')));
      if (mappedTasks.length === 0) {
        lines.push('- (no tasks)', '');
        continue;
      }
      lines.push('| Task | Status | Dev Docs |', '| --- | --- | --- |');
      for (const task of mappedTasks) {
        const label = `${task?.id || ''} ${task?.slug || ''}`.trim();
        lines.push(
          `| ${markdownCell(label)} | ${markdownCell(task?.status)} | ${markdownCell(task?.dev_docs_path)} |`
        );
      }
      lines.push('');
    }
  }
  lines.push('<!-- AUTO-GENERATED:END feature-map -->', '');
  return lines.join('\n');
}

